function normaliseProduct(seed: SeedProduct): Product {
  const unit = seed.unit ?? 'kg';
  return {
    ...seed,
    unit,
    tags: seed.tags ?? [],
    highlights: seed.highlights ?? seed.benefits.slice(0, 3),
    isNew: seed.isNew ?? false,
    sortOrder: seed.sortOrder ?? 100,
    weightOptions: seed.weightOptions.map((variant) => ({
      ...variant,
      unit: variant.unit ?? unit,
    })),
  };
}

export const PRODUCT_SEED: Product[] = RAW_PRODUCT_SEED.map(normaliseProduct);
