import { build } from 'esbuild';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

await build({
  entryPoints: [path.join(root, 'backend/server/serverless.ts')],
  outfile: path.join(root, 'api/index.js'),
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node20',
  packages: 'external',
  banner: { js: '// Generated by `npm run build:api`. Do not edit by hand.' },
  logLevel: 'info',
});
